def table(headers,rows,widths=None):
    t=doc.add_table(rows=1, cols=len(headers)); t.alignment=WD_TABLE_ALIGNMENT.CENTER
    t.autofit=False
    if widths is None: widths=[16.4/len(headers)]*len(headers)
    for c,w in zip(t.columns,widths): c.width=Cm(w)
    for c,txt in zip(t.rows[0].cells,headers): c.text=txt
    for row in rows:
        for c,txt in zip(t.add_row().cells,row): c.text=str(txt)
    for ri,row in enumerate(t.rows):
        trpr=row._tr.get_or_add_trPr()
        no=OxmlElement('w:cantSplit'); trpr.append(no)
        if ri==0:
            rep=OxmlElement('w:tblHeader'); trpr.append(rep)
        for ci,c in enumerate(row.cells):
            c.width=Cm(widths[ci]); c.vertical_alignment=WD_CELL_VERTICAL_ALIGNMENT.CENTER
            tcpr=c._tc.get_or_add_tcPr()
            mar=OxmlElement('w:tcMar')
            for edge in ['top','left','bottom','right']:
                e=OxmlElement('w:'+edge); e.set(qn('w:w'),'70'); e.set(qn('w:type'),'dxa'); mar.append(e)
            tcpr.append(mar)
            borders=OxmlElement('w:tcBorders')
            for edge in ['top','left','bottom','right']:
                e=OxmlElement('w:'+edge); e.set(qn('w:val'),'single'); e.set(qn('w:sz'),'4'); e.set(qn('w:color'),'D9D9D9'); borders.append(e)
            tcpr.append(borders)
            if ri==0:
                sh=OxmlElement('w:shd'); sh.set(qn('w:fill'),'E8EDF2'); tcpr.append(sh)
            for para in c.paragraphs:
                para.paragraph_format.space_after=Pt(2); para.paragraph_format.space_before=Pt(2)
                para.paragraph_format.line_spacing=Pt(12.5)
                for r in para.runs: r.font.size=Pt(9); r.bold=ri==0
    gap=p(''); gap.paragraph_format.space_after=Pt(2); gap.paragraph_format.line_spacing=Pt(2)
    return t
